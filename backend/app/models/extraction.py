"""Extraction result database model."""

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from sqlalchemy import String, Integer, DateTime, Text, JSON, ForeignKey, Enum as SQLEnum
from sqlalchemy.orm import Mapped, mapped_column, relationship
from backend.app.database import Base

if TYPE_CHECKING:
    from backend.app.models.document import Document
    from backend.app.models.provenance import FieldProvenance


class ExtractionMethod(str, Enum):
    RULE_BASED = "rule_based"
    LLM = "llm"
    HYBRID = "hybrid"
    MANUAL = "manual"


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class ExtractionResult(Base):
    """Represents an extraction attempt on a document (by rule parser, local LLM, or user)."""

    __tablename__ = "extraction_results"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
        index=True,
    )
    document_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("documents.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Core extracted fields
    vendor: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    invoice_number: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    date: Mapped[Optional[str]] = mapped_column(String(10), nullable=True)  # YYYY-MM-DD
    due_date: Mapped[Optional[str]] = mapped_column(String(10), nullable=True)  # YYYY-MM-DD
    currency: Mapped[Optional[str]] = mapped_column(String(3), nullable=True)  # ISO 4217, e.g. USD, EUR, INR

    # Monetary values stored in integer minor units (paise/cents). None if not found/missing.
    subtotal: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    tax: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    total: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    category: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Structured line items (list of {description, quantity, unit_price, amount})
    line_items: Mapped[Optional[List[Dict[str, Any]]]] = mapped_column(JSON, nullable=True)

    # Extraction metadata
    extraction_method: Mapped[ExtractionMethod] = mapped_column(
        SQLEnum(ExtractionMethod, name="extraction_method_enum", native_enum=False),
        default=ExtractionMethod.RULE_BASED,
        nullable=False,
    )
    model_name: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    # Validation diagnostics generated by guard checks
    validation_issues: Mapped[Optional[List[str]]] = mapped_column(JSON, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        onupdate=utc_now,
        nullable=False,
    )

    # Relationships
    document: Mapped["Document"] = relationship("Document", back_populates="extractions")
    field_provenances: Mapped[List["FieldProvenance"]] = relationship(
        "FieldProvenance",
        back_populates="extraction_result",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return (
            f"<ExtractionResult(id={self.id}, doc={self.document_id}, "
            f"vendor={self.vendor}, total={self.total}, cur={self.currency})>"
        )
